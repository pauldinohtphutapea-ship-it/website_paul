    if (requestedMaterial === "uts-essay-tti") {
        document.title = "UTS Essay TTI | Paul Dino";

        addTextElement(
            detailContent,
            "p",
            "UTS ESSAY TTI",
            "eyebrow"
        );

        addTextElement(
            detailContent,
            "h1",
            "UTS Essay TTI"
        );

        let currentCategory = "";

        utsEssayTTI.forEach((item) => {
            if (item.category !== currentCategory) {
                currentCategory = item.category;

                addTextElement(
                    detailContent,
                    "h2",
                    currentCategory
                );
            }

            addTextElement(
                detailContent,
                "h3",
                `${item.number}. ${item.question}`
            );

            addTextElement(
                detailContent,
                "p",
                item.answer
            );
        });

        const backLink = document.createElement("a");
        backLink.className = "material-nav-link";
        backLink.href = "index.html";
        backLink.textContent = "← Kembali ke Halaman Profil";

        detailContent.appendChild(backLink);

    } else {
        // ==============================
        // HALAMAN MATERI 1–7
        // ==============================
        const selectedMaterial = Number(requestedMaterial);

        const material = Number.isInteger(selectedMaterial)
            ? materials[selectedMaterial - 1]
            : null;

        if (material) {
            document.title =
                `${material.title} - ${material.subtitle} | Paul Dino`;

            addTextElement(
                detailContent,
                "p",
                "TREN TEKNOLOGI INFORMASI",
                "eyebrow"
            );

            addTextElement(
                detailContent,
                "h1",
                material.title
            );

            addTextElement(
                detailContent,
                "p",
                material.subtitle,
                "detail-subtitle"
            );

            material.sections.forEach((section) => {
                renderSection(detailContent, section);
            });

            const navigation = document.createElement("div");
            navigation.className = "material-navigation";

            if (selectedMaterial > 1) {
                const previous = document.createElement("a");
                previous.className = "material-nav-link";
                previous.href =
                    `index.html?materi=${selectedMaterial - 1}`;
                previous.textContent = "← Materi Sebelumnya";

                navigation.appendChild(previous);
            }

            if (selectedMaterial < materials.length) {
                const next = document.createElement("a");
                next.className = "material-nav-link";
                next.href =
                    `index.html?materi=${selectedMaterial + 1}`;
                next.textContent = "Materi Selanjutnya →";

                navigation.appendChild(next);
            }

            detailContent.appendChild(navigation);

        } else {
            addTextElement(
                detailContent,
                "h1",
                "Materi tidak ditemukan"
            );

            addTextElement(
                detailContent,
                "p",
                "Materi yang kamu cari tidak tersedia. Silakan kembali ke halaman profil."
            );
        }
    }
