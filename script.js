function addTextElement(parent, tagName, text, className = "") {
    const element = document.createElement(tagName);
    element.textContent = text;

    if (className) {
        element.className = className;
    }

    parent.appendChild(element);
    return element;
}

function renderSection(parent, section) {
    addTextElement(parent, "h2", section.heading);

    if (section.paragraphs) {
        section.paragraphs.forEach(text => {
            addTextElement(parent, "p", text);
        });
    }

    if (section.bullets) {
        const list = document.createElement("ul");

        section.bullets.forEach(text => {
            addTextElement(list, "li", text);
        });

        parent.appendChild(list);
    }

    if (section.paragraphsAfter) {
        section.paragraphsAfter.forEach(text => {
            addTextElement(parent, "p", text);
        });
    }

    if (section.subsections) {
        section.subsections.forEach(subsection => {
            renderSection(parent, subsection);
        });
    }
}


